"""Writes src/isoline/c/WasmVectors.cpp, the definitions of wasm.h's vector functions, from the rows of
src/isoline/c/detail/VectorRows.def, and checks that the checked-in file is what the rows give.

Every exported symbol of the C API has exactly one definition the boundary lint can read (c-api-noexcept.py
--symbols), so the five functions of each vector family are written out here rather than made by a macro at
compile time: a family is one row of VectorRows.def, and the file follows from the rows.

write   writes the file from the rows.
check   fails when the file differs from what the rows give (run `write`), and, given --header, when the rows
        are not exactly the vector families wasm.h declares, each of the ownership wasm.h gives its elements
        (`*`, an own pointer, is exactly the Owned rows).

Usage:
  c-api-vectors.py write --rows <VectorRows.def> --output <WasmVectors.cpp>
  c-api-vectors.py check --rows <VectorRows.def> --output <WasmVectors.cpp> [--header <wasm.h>]
"""

import argparse
import pathlib
import re
import sys

OWNERSHIPS = ("Plain", "Value", "Owned")

ROW = re.compile(r"^ISOLINE_VECTOR_ROW\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*,\s*([A-Za-z]+)\s*\)\s*$")

# wasm.h declares a family with WASM_DECLARE_VEC(name, ptr_or_none), or with WASM_DECLARE_TYPE(name), which
# declares the family of own pointers. The macros' own definitions (`#define ...`) are no declarations.
HEADER_VECTOR = re.compile(r"^WASM_DECLARE_VEC\(\s*(\w+)\s*,\s*(\*?)\s*\)", re.MULTILINE)
HEADER_TYPE = re.compile(r"^WASM_DECLARE_TYPE\(\s*(\w+)\s*\)", re.MULTILINE)

PROLOGUE = """\
// SPDX-License-Identifier: Apache-2.0
//
// Generated by scripts/c-api-vectors.py from detail/VectorRows.def: do not edit. Add a row there and run,
// from the repository's root,
//     python3 scripts/c-api-vectors.py write --rows src/isoline/c/detail/VectorRows.def --output <this file>
// (the c-api-vectors lint fails while this file differs from what the rows give).
//
// wasm.h's vectors: five functions per family, each one boundary() call of the family's operation in
// detail/Vector.hpp, which says what each does with hostile sizes and missing data. Out of host memory, a
// vector made or copied is the empty vector.

#include <cstddef>

#include <isoline/c/detail/Boundary.hpp>
#include <isoline/c/detail/Handles.hpp>
#include <isoline/c/detail/Vector.hpp>
#include <isoline/c/isoline.h>

namespace detail = isoline::c::detail;
"""

FAMILY = """
// wasm_{name}_vec_t: {description}

void wasm_{name}_vec_new_empty(wasm_{name}_vec_t* out)
{{
    detail::boundary([&] {{ detail::emptyVector(out); }}, [] {{}});
}}

void wasm_{name}_vec_new_uninitialized(wasm_{name}_vec_t* out, size_t size)
{{
    detail::boundary([&] {{ detail::newUninitializedVector<detail::ElementOwnership::{ownership}>(out, size); }},
                     [&] {{ detail::emptyVector(out); }});
}}

void wasm_{name}_vec_new(wasm_{name}_vec_t* out, size_t size, {element} const data[])
{{
    detail::boundary([&] {{ detail::newVector<detail::ElementOwnership::{ownership}>(out, size, data); }},
                     [&] {{ detail::emptyVector(out); }});
}}

void wasm_{name}_vec_copy(wasm_{name}_vec_t* out, wasm_{name}_vec_t const* source)
{{
    detail::boundary([&] {{ detail::copyVector<detail::ElementOwnership::{ownership}>(out, source); }},
                     [&] {{ detail::emptyVector(out); }});
}}

void wasm_{name}_vec_delete(wasm_{name}_vec_t* vector)
{{
    detail::boundary([&] {{ detail::deleteVector<detail::ElementOwnership::{ownership}>(vector); }}, [] {{}});
}}
"""

DESCRIPTIONS = {
    "Plain": "its elements own nothing.",
    "Value": "a value of a reference kind owns its reference, deleted and copied with it.",
    "Owned": "its elements are own pointers, deleted with it and deep-copied with it.",
}


def readRows(path):
    """The rows of VectorRows.def, in their order, and the problems of their form."""
    rows = []
    problems = []
    for number, line in enumerate(pathlib.Path(path).read_text(encoding="utf-8").splitlines(), start=1):
        if not line.startswith("ISOLINE_VECTOR_ROW"):
            continue
        match = ROW.match(line)
        if match is None:
            problems.append(f"{path}:{number}: '{line}' is not ISOLINE_VECTOR_ROW(name, ownership)")
            continue
        name, ownership = match.groups()
        if ownership not in OWNERSHIPS:
            problems.append(f"{path}:{number}: {name}: '{ownership}' is no ownership ({', '.join(OWNERSHIPS)})")
            continue
        if any(name == row[0] for row in rows):
            problems.append(f"{path}:{number}: {name}: a second row of the family")
            continue
        rows.append((name, ownership))
    if not rows and not problems:
        problems.append(f"{path}: no row")
    return rows, problems


def generated(rows):
    """The text of WasmVectors.cpp for the rows."""
    families = []
    for name, ownership in rows:
        element = f"wasm_{name}_t*" if ownership == "Owned" else f"wasm_{name}_t"
        families.append(FAMILY.format(name=name, ownership=ownership, element=element,
                                      description=DESCRIPTIONS[ownership]))
    return PROLOGUE + "".join(families)


def headerFamilies(text):
    """The vector families a wasm.h declares, by name: whether its elements are own pointers."""
    families = {name: pointer == "*" for name, pointer in HEADER_VECTOR.findall(text)}
    families.update({name: True for name in HEADER_TYPE.findall(text)})
    return families


def headerProblems(rows, families):
    """How the rows differ from the families wasm.h declares."""
    problems = []
    byName = dict(rows)
    for name, pointer in sorted(families.items()):
        if name not in byName:
            problems.append(f"wasm_{name}_vec_t: declared by wasm.h, and no row of VectorRows.def")
        elif pointer != (byName[name] == "Owned"):
            kind = "own pointers" if pointer else "no pointers"
            problems.append(f"wasm_{name}_vec_t: wasm.h's elements are {kind}, and the row says {byName[name]}")
    problems += [f"wasm_{name}_vec_t: a row of VectorRows.def, and wasm.h declares no such family"
                 for name, _ in rows if name not in families]
    return problems


def main(arguments):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("write", "check"))
    parser.add_argument("--rows", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--header")
    options = parser.parse_args(arguments)

    rows, problems = readRows(options.rows)
    if options.header is not None:
        problems += headerProblems(rows, headerFamilies(pathlib.Path(options.header).read_text(encoding="utf-8")))
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1
    text = generated(rows)
    output = pathlib.Path(options.output)
    if options.command == "write":
        output.write_text(text, encoding="utf-8", newline="\n")
        print(f"c-api-vectors: wrote {output}, {len(rows)} families")
        return 0
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        print(f"{output}: differs from what {options.rows} gives; run c-api-vectors.py write", file=sys.stderr)
        return 1
    print(f"c-api-vectors: {output} is what the {len(rows)} rows give")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
