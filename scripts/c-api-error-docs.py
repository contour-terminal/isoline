"""Writes the Errors section of docs/c-api.md from the sources that define it, and checks that the checked-in
section is what they give.

The codes, their values and what each means come from error.h's isoline_error_code_enum; which codes report
a detail, and from which family, from ErrorCodeRows (src/isoline/c/detail/ErrorRows.hpp); the published
detail numbers from the pinned lists of src/isoline/c/ErrorDetails_test.cpp, which hold every family's
numbering fixed. A code or a detail appended there is a row here once `write` runs, and the lint fails
until it does.

write   rewrites the section, between its markers, from the sources.
check   fails when the section differs from what the sources give (run `write`).

Usage:
  c-api-error-docs.py write --source <repository root>
  c-api-error-docs.py check --source <repository root>
"""

import argparse
import pathlib
import re
import sys

BEGIN = "<!-- c-api-error-docs: begin (generated by scripts/c-api-error-docs.py; do not edit) -->"
END = "<!-- c-api-error-docs: end -->"

ERROR_H = "src/isoline/c/error.h"
ERROR_ROWS = "src/isoline/c/detail/ErrorRows.hpp"
PINNED = "src/isoline/c/ErrorDetails_test.cpp"
DOCS = "docs/c-api.md"

# /** What it means. */ ISOLINE_ERROR_NAME = 7,
CODE = re.compile(r"/\*\*\s*(.*?)\s*\*/\s*(ISOLINE_ERROR_[A-Z0-9_]+)\s*=\s*(\d+)\s*,", re.S)
# { .code = ISOLINE_ERROR_NAME, .name = "...", .family = DetailFamily::Family }
CODE_ROW = re.compile(r"\.code\s*=\s*(ISOLINE_ERROR_[A-Z0-9_]+)\s*,.*?\.family\s*=\s*DetailFamily::(\w+)", re.S)
# std::to_array<Pinned<namespace::Family>>({ { 1, namespace::Family::Name }, ... })
PINNED_LIST = re.compile(r"Pinned<[\w:]*::(\w+)>>\(\{(.*?)\}\)\)", re.S)
PINNED_ROW = re.compile(r"\{\s*(\d+)\s*,\s*[\w:]+::(\w+)\s*\}")


def codes(text):
    """The codes of error.h, in value order: (name, value, meaning)."""
    enum = text[text.index("enum isoline_error_code_enum") :]
    enum = enum[: enum.index("};")]
    # The meaning, without the detail it reports (the table's own column).
    rows = [(name, int(value), " ".join(meaning.split(";")[0].split()).rstrip(".") + ".")
            for meaning, name, value in CODE.findall(enum)]
    if not rows:
        raise SystemExit(f"c-api-error-docs: {ERROR_H} defines no code")
    return rows


def families(text):
    """The family of each code that has one: {code name: family}."""
    return {code: family for code, family in CODE_ROW.findall(text) if family != "None"}


def pinned(text):
    """Every family's published details, in detail order: {family: [(detail, enumerator)]}."""
    result = {}
    for family, body in PINNED_LIST.findall(text):
        result[family] = [(int(detail), name) for detail, name in PINNED_ROW.findall(body)]
    return result


def section(source):
    """The Errors section the sources give, markers included."""
    code_rows = codes((source / ERROR_H).read_text(encoding="utf-8"))
    family_of = families((source / ERROR_ROWS).read_text(encoding="utf-8"))
    details = pinned((source / PINNED).read_text(encoding="utf-8"))
    for code, family in family_of.items():
        if family not in details:
            raise SystemExit(f"c-api-error-docs: {code}'s family {family} has no pinned list in {PINNED}")

    lines = [BEGIN, "", "| Code | Value | Meaning | Detail |", "|---|---|---|---|"]
    for name, value, meaning in code_rows:
        family = family_of.get(name)
        detail = f"[{family}](#details-{family.lower()})" if family else "always 0"
        lines.append(f"| `{name}` | {value} | {meaning} | {detail} |")
    used = []
    for name, _, _ in code_rows:
        family = family_of.get(name)
        if family and family not in used:
            used.append(family)
    for family in used:
        users = ", ".join(f"`{name}`" for name, _, _ in code_rows if family_of.get(name) == family)
        lines += ["", f'<a id="details-{family.lower()}"></a>', f"### Details: {family}", "",
                  f"Reported with {users}.", "", "| Detail | Cause |", "|---|---|"]
        lines += [f"| {detail} | `{enumerator}` |" for detail, enumerator in details[family]]
    lines += ["", END]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("mode", choices=("write", "check"))
    parser.add_argument("--source", required=True, type=pathlib.Path, help="the repository's root")
    arguments = parser.parse_args()

    docs = arguments.source / DOCS
    text = docs.read_text(encoding="utf-8")
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SystemExit(f"c-api-error-docs: {DOCS} must hold the section's markers once each")
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    wanted = section(arguments.source)
    if arguments.mode == "write":
        docs.write_text(text[:start] + wanted + text[stop:], encoding="utf-8", newline="\n")
        return 0
    if text[start:stop] != wanted:
        print(f"c-api-error-docs: {DOCS}'s Errors section differs from what {ERROR_H}, {ERROR_ROWS} and "
              f"{PINNED} give; run\n    python3 scripts/c-api-error-docs.py write --source .", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
