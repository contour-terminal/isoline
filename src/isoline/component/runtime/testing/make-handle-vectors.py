"""Writes HandleVectors.inc: what definitions.py's handle table and resource operations do for a fixed
pseudo-random sequence of operations on one component instance's table: canon_resource_new,
canon_resource_drop and canon_resource_rep, lift_own, lift_borrow (through one Subtask at a time, its
deliver_resolve ending its lends), lower_own and lower_borrow (into one Task at a time, its return_
ending it).

Two resource types: type 1 implemented elsewhere (a host type in the C++ test), type 2 implemented by
the instance itself, so a borrow of it lowered there is its representation. Every own drop calls the
type's destructor, which records the representation.

definitions.py removes a handle before it checks it (lift_own, canon_resource_drop); Isoline checks
first, so that a trap changes nothing. A trap locks the store down, after which nothing observes the
difference, so the script restores the state from before each operation that traps and goes on, and
the vectors pin each outcome against an unchanged table.

Usage: make-handle-vectors.py <path to design/mvp/canonical-abi/definitions.py> > HandleVectors.inc
The vectors in the tree come from definitions.py at the component-model pin f78ac03c.
"""

import copy
import importlib.util
import random
import sys

OPERATIONS = 4000
SEED = 13


def load_definitions(path):
    spec = importlib.util.spec_from_file_location("definitions", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Store:
    """Lifts and lowers a destructor as a plain call, and locks nothing down."""

    def lift(self, f, ft, opts, inst):
        return f

    def lower(self, f, ft, opts, inst):
        return lambda args: f(args)

    def lock_down(self):
        pass


class Instance:
    def __init__(self, d):
        self.store = Store()
        self.handles = d.Table()
        self.may_leave = True


class Context:
    def __init__(self, inst, borrow_scope):
        self.inst = inst
        self.borrow_scope = borrow_scope


class Handle:
    def __init__(self, rt):
        self.rt = rt


def main():
    d = load_definitions(sys.argv[1])
    rng = random.Random(SEED)
    inst = Instance(d)
    d.current_instance = lambda: inst
    destroyed = []
    elsewhere = d.ResourceType(object(), lambda args: destroyed.append(args[0]) or [])
    itself = d.ResourceType(inst, lambda args: destroyed.append(args[0]) or [])
    types = {1: elsewhere, 2: itself}
    state = {"task": d.Task(None, None, inst, None, lambda result: None), "subtask": d.Subtask()}

    def index():
        roll = rng.random()
        if roll < 0.03:
            return 0xFFFFFFFF
        return rng.randrange(0, len(inst.handles.array) + 2)

    def run(op, t, arg):
        rt = types[t]
        handle = Handle(rt)
        if op == "New":
            return d.canon_resource_new(rt, arg)[0]
        if op == "Drop":
            d.canon_resource_drop(rt, arg)
            return 0
        if op == "Rep":
            return d.canon_resource_rep(rt, arg)[0]
        if op == "LiftOwn":
            return d.lift_own(Context(inst, None), arg, handle)
        if op == "LiftBorrow":
            return d.lift_borrow(Context(inst, state["subtask"]), arg, handle)
        if op == "Resolve":
            state["subtask"].resolve(d.Subtask.State.RETURNED, [])
            state["subtask"].deliver_resolve()
            state["subtask"] = d.Subtask()
            return 0
        if op == "LowerOwn":
            return d.lower_own(Context(inst, None), arg, handle)
        if op == "LowerBorrow":
            return d.lower_borrow(Context(inst, state["task"]), arg, handle)
        if op == "Return":
            state["task"].return_([])
            state["task"] = d.Task(None, None, inst, None, lambda result: None)
            return 0
        raise AssertionError(op)

    choices = ["New"] * 6 + ["Drop"] * 8 + ["Rep"] * 3 + ["LiftOwn"] * 3 + ["LiftBorrow"] * 3 + \
        ["Resolve"] + ["LowerOwn"] * 2 + ["LowerBorrow"] + ["Return"] * 2
    print("// SPDX-License-Identifier: Apache-2.0")
    print("// Generated by make-handle-vectors.py from definitions.py at the component-model pin f78ac03c:")
    print("// one instance's handle table under the resource built-ins, lift_own/lift_borrow and")
    print("// lower_own/lower_borrow. Do not edit.")
    for _ in range(OPERATIONS):
        op = rng.choice(choices)
        t = rng.choice([1, 2])
        arg = rng.randrange(1, 1000) if op in ("New", "LowerOwn", "LowerBorrow") else index()
        if op in ("Resolve", "Return"):
            t = 1
            arg = 0
        saved = copy.deepcopy((inst.handles, state["task"], state["subtask"]),
                              {id(inst): inst, id(elsewhere): elsewhere, id(itself): itself})
        destroyed.clear()
        try:
            value = run(op, t, arg)
            outcome = "Value"
        except d.Trap:
            inst.handles, state["task"], state["subtask"] = saved
            value = 0
            outcome = "Trap"
            destroyed.clear()
        assert len(destroyed) <= 1
        rep = destroyed[0] if destroyed else "NoRep"
        print(f"{{ Op::{op}, {t}, {arg}U, Outcome::{outcome}, {value}U, {rep} }},")


if __name__ == "__main__":
    main()
