"""Writes TranscodeVectors.inc: what definitions.py's store_string_into_range does for each source
encoding, destination encoding and string, run against a realloc that behaves as FakeGuestMemory's
(canonical/testing/GuestDoubles.hpp): a bump allocator from address 1024 in a 4096-byte memory that
grows past its end and copies the old block's bytes into every new block.

Usage: make-transcode-vectors.py <path to design/mvp/canonical-abi/definitions.py> > TranscodeVectors.inc
The vectors in the tree come from definitions.py at the component-model pin f78ac03c.
"""

import importlib.util
import sys

HEAP_START = 1024
MEMORY_SIZE = 4096

# Every simple form a source string takes: its encoding, and for latin1+utf16 whether it is tagged UTF-16.
SOURCES = [("utf8", False), ("utf16", False), ("latin1+utf16", False), ("latin1+utf16", True)]
DESTINATIONS = ["utf8", "utf16", "latin1+utf16"]

# run_tests.py's fun_strings, the brief's three ("aé😀", pure ASCII, pure Latin-1), and a lone emoji.
STRINGS = ["", "a", "hi", "\x00", "a\x00b", "\x80", "\x80b", "ab\xefc", "ǿy", "xyǿ", "a퟿b",
           "a˿Ͽӿbc", "", "abc", "abcdef", "a\xe9\U0001f600", "hello",
           "h\xe9llo", "\U0001f600"]

CPP_ENCODING = {"utf8": "Utf8", "utf16": "Utf16", "latin1+utf16": "Latin1Utf16"}


def load_definitions(path):
    spec = importlib.util.spec_from_file_location("definitions", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Memory(bytearray):
    def ptr_type(self):
        return "i32"

    def ptr_size(self):
        return 4


class Options:
    def __init__(self, encoding):
        self.memory = Memory(MEMORY_SIZE)
        self.string_encoding = encoding


class Context:
    """What store_string_into_range reaches of a LiftLowerContext: its options, allocate and reallocate."""

    def __init__(self, definitions, encoding):
        self.definitions = definitions
        self.opts = Options(encoding)
        self.next = HEAP_START
        self.reallocations = []

    def reallocate(self, old, old_size, alignment, new_size):
        memory = self.opts.memory
        result = (self.next + alignment - 1) // alignment * alignment
        end = result + new_size
        if end > len(memory):
            memory.extend(bytes(end - len(memory)))
        if old != 0:
            kept = min(old_size, new_size)
            memory[result:result + kept] = memory[old:old + kept]
        self.next = end
        self.reallocations.append((old, old_size, alignment, new_size, result))
        self.definitions.trap_if(result != self.definitions.align_to(result, alignment))
        self.definitions.trap_if(result + new_size > len(memory))
        return result

    def allocate(self, alignment, byte_length):
        return self.reallocate(0, 0, alignment, byte_length)


def source_of(text, encoding, tagged):
    """The bytes and tagged code units of text in a source form, or None when it cannot hold text."""
    tag = 1 << 31
    if encoding == "utf8":
        data = text.encode("utf-8")
        return data, len(data)
    if encoding == "utf16" or tagged:
        data = text.encode("utf-16-le")
        return data, len(data) // 2 | (tag if tagged else 0)
    try:
        data = text.encode("latin-1")
    except UnicodeEncodeError:
        return None
    return data, len(data)


def destination_bytes(memory, encoding, pointer, tagged_code_units):
    tag = 1 << 31
    if encoding == "utf8" or (encoding == "latin1+utf16" and not tagged_code_units & tag):
        length = tagged_code_units
    else:
        length = 2 * (tagged_code_units & ~tag)
    return bytes(memory[pointer:pointer + length])


def main():
    definitions = load_definitions(sys.argv[1])
    print("// SPDX-License-Identifier: Apache-2.0")
    print("// Generated by make-transcode-vectors.py from definitions.py at the component-model pin f78ac03c:")
    print("// store_string_into_range, against a realloc that behaves as FakeGuestMemory's. Do not edit.")
    count = 0
    for encoding, tagged in SOURCES:
        for destination in DESTINATIONS:
            for text in STRINGS:
                source = source_of(text, encoding, tagged)
                if source is None:
                    continue
                data, tagged_code_units = source
                context = Context(definitions, destination)
                value = (text, encoding, tagged_code_units)
                pointer, result_units = definitions.store_string_into_range(context, value)
                stored = destination_bytes(context.opts.memory, destination, pointer, result_units)
                reallocations = ", ".join(
                    "{{ {}, {}, {}, {}, {} }}".format(*row) for row in context.reallocations)
                print("{{ StringEncoding::{}, {:#x}, \"{}\", StringEncoding::{}, {{ {} }}, {}, {:#x}, \"{}\" }},".format(
                    CPP_ENCODING[encoding], tagged_code_units, data.hex(), CPP_ENCODING[destination],
                    reallocations, pointer, result_units, stored.hex()))
                count += 1
    print("// {} vectors".format(count))


if __name__ == "__main__":
    main()
